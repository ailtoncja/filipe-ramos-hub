export const FONTES_ORDENADAS: Fonte[] = FONTES.toSorted((a, b) =>
  a.nomeExibicao.localeCompare(b.nomeExibicao, 'pt-BR'),
);

export const MAPA_FONTES: ReadonlyMap<string, Fonte> = new Map(
  FONTES.map((fonte) => [fonte.nome, fonte]),
);

export const FONTES_OFICIAIS_SET: ReadonlySet<string> = new Set(
  FONTES.filter((f) => f.categoria === 'oficial').map((f) => f.nome),
);

export function nomeExibicaoDaFonte(nome: string): string {
  return MAPA_FONTES.get(nome)?.nomeExibicao ?? nome;
}

export function ehFonteOficial(fontes: string[]): boolean {
  return fontes.some((f) => FONTES_OFICIAIS_SET.has(f));
}
